describe('TranscriptCompactor', () => {
  it('gives exactly the joined-then-cut text, whatever the message sizes', () => {
    let seed = 7;
    const rand = () => (seed = (seed * 48271) % 2147483647) / 2147483647;
    for (const maxChars of [50, 333, 2000]) {
      const parts: string[] = [];
      const c = new TranscriptCompactor({ maxChars });
      for (let i = 0; i < 120; i++) {
        const text = `m${i} ${'abc'.repeat(Math.floor(rand() * 60))}`;
        const role = rand() < 0.5 ? 'user' : 'assistant';
        parts.push(`${role === 'user' ? 'User' : 'Assistant'}: ${text}`);
        c.add(role, text);
        const full = parts.join('\n\n');
        const head = Math.floor(maxChars * 0.3);
        const expected =
          full.length <= maxChars
            ? full
            : `${full.slice(0, head)}\n\n… (${full.length - maxChars} characters left out) …\n\n${full.slice(-(maxChars - head))}`;
        expect(c.result()).toBe(expected);
      }
    }
    expect(compactTranscript('')).toBe('');
  });
});
