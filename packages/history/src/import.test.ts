describe('huge messages', () => {
  it('imports a file with a 9 MB line, its secrets masked on both sides of the message cut', async () => {
    const root = realpathSync(mkdtempSync(join(tmpdir(), 'loop-import-big-')));
    try {
      const folder = join(root, 'big');
      mkdirSync(folder);
      const dir = join(root, 'projects', encodeProjectDir(folder));
      mkdirSync(dir, { recursive: true });
      const aws = SECRET_SAMPLES.find((x) => x.name === 'AWS secret key')!.token;
      const gh = SECRET_SAMPLES[0]!.token;
      // A token right at each place the message is cut, and a private key across the tail cut.
      const keyLines = PRIVATE_KEY.split('\n');
      const huge =
        'U'.repeat(MESSAGE_KEEP - 10) +
        ` ${gh} ` +
        'U'.repeat(9 * 1024 * 1024) +
        ` ${keyLines[0]}\n${keyLines[1]}\n` +
        'V'.repeat(MESSAGE_KEEP - 30) +
        `\n${keyLines.slice(2).join('\n')} then ${aws} done`;
      const path = join(dir, `${id(1)}.jsonl`);
      writeFileSync(
        path,
        [user('Paste the log', '2026-09-01T09:00:00Z'), user(huge, '2026-09-01T09:01:00Z')].join('\n'),
      );
      utimesSync(path, OLD, OLD);
      const store = openStore({ clock: new FakeClock('2026-10-18T09:00:00.000Z') });
      const project = store.projects.create({ name: 'big', kind: 'folder', folderPath: folder });
      const summary = await importProjectSessions(store, project, {
        projectsDir: join(root, 'projects'),
        maxChars: 2_000_000,
      });
      expect(summary.skipped.unreadable).toBe(0);
      expect(summary.imported).toHaveLength(1);
      const text = store.history.list({ kind: 'transcript' })[0]!.text;
      expect(text).toMatch(/characters of this message left out/);
      expect(text.length).toBeLessThan(2 * MESSAGE_KEEP + 10_000);
      for (const t of [gh, aws]) expect(holdsNoPieceOf(text, t)).toBe(true);
      expect(text).not.toContain('KEYBODY');
      expect(text).not.toContain('b3BlbnNzaC1rZXktdjE');
      expect(text).toContain('done');
      store.close();
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it('parses, strips noise and redacts a 1 MB adversarial message in well under a second', () => {
    const redact = (t: string) => maskEdgeFragments(redactSecrets(t));
    for (const body of [
      '<system-reminder>'.repeat(60_000),
      '<command-name>x</command-args>'.repeat(30_000),
      'a.'.repeat(500_000),
      'token.'.repeat(170_000),
      'x'.repeat(MESSAGE_MAX + 5),
    ]) {
      const t0 = performance.now();
      const parsed = parseTranscriptLine(JSON.stringify({ type: 'user', message: { content: body } }));
      expect(parsed.kind).toBe('message');
      const c = new TranscriptCompactor({ redact });
      if (parsed.kind === 'message') c.add('user', parsed.text);
      c.result();
      expect(performance.now() - t0).toBeLessThan(1000);
    }
    expect(stripNoise('a<system-reminder>x</system-reminder>b<system-reminder>open')).toBe(
      'ab<system-reminder>open',
    );
    expect(stripNoise('<command-name>/clear</command-name>keep<command-args>x</command-args>')).toBe('keep');
  }, 30_000);

  it('cuts a huge message at whitespace and masks each piece', () => {
    const redact = (t: string) => maskEdgeFragments(redactSecrets(t));
    const gh = SECRET_SAMPLES[0]!.token;
    for (const shift of [-40, -20, -5, 0, 5]) {
      const text = `${'word '.repeat((MESSAGE_KEEP + shift) / 5)}${gh}${'x'.repeat(MESSAGE_MAX)} end`;
      expect(holdsNoPieceOf(redactMessage(text, redact), gh)).toBe(true);
    }
    expect(redactMessage('short text', redact)).toBe('short text');
  });
});

describe('redaction around the transcript cut', () => {
  const redact = (t: string) => maskEdgeFragments(redactSecrets(t));
  const filler = (n: number) => 'x '.repeat(n).slice(0, n);

  it('never stores a piece of a token, wherever the head or tail cut falls', () => {
    for (const maxChars of [200, 997]) {
      const head = Math.floor(maxChars * 0.3);
      const tailLength = maxChars - head;
      for (const sample of SECRET_SAMPLES) {
        const t = sample.token;
        // Head cut: "User: " + filler + " " + token, with the cut at every position in and around the token.
        for (let n = Math.max(0, head - 6 - t.length - 4); n <= head - 6 + 2; n++) {
          const c = new TranscriptCompactor({ maxChars, redact });
          c.add('user', `${filler(n)} ${t} end`);
          c.add('assistant', filler(maxChars * 2));
          const out = c.result();
          expect(holdsNoPieceOf(out, t), `${sample.name} head n=${n}: ${out.slice(0, head + 5)}`).toBe(true);
        }
        // Tail cut: the token near the end, with the cut at every position in and around it.
        for (let m = Math.max(0, tailLength - t.length - 2); m <= tailLength + 2; m++) {
          const c = new TranscriptCompactor({ maxChars, redact });
          c.add('user', filler(maxChars * 2));
          c.add('assistant', `${filler(50)} ${t}${filler(m)}`);
          const out = c.result();
          expect(holdsNoPieceOf(out, t), `${sample.name} tail m=${m}`).toBe(true);
        }
      }
    }
  });

  it('stores no token prefix when the cut lands inside a token (importer path)', () => {
    const t = SECRET_SAMPLES[0]!.token;
    const c = new TranscriptCompactor({ maxChars: 2000, redact });
    c.add('user', `${'x'.repeat(600 - 'User: '.length - 12)} ${t} end`);
    c.add('assistant', 'z'.repeat(5000));
    expect(c.result()).not.toContain('ghp_');
  });
});

